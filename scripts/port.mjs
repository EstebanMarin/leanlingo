// Regenerates LeanLingo/Exercises.lean and LeanLingo/Answers.lean from the
// LeanLingo question data (https://github.com/kjusino/leanlingo, MIT).
//
//   node scripts/port.mjs            # fetch data at the pinned commit
//   node scripts/port.mjs <dataDir>  # read questions/worlds/practice.json locally

import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const REPO = 'kjusino/leanlingo';
const COMMIT = 'c99ced0c45ac68573e0bdd9bcede6aed7fc17c6c';

async function load(name) {
  const dir = process.argv[2];
  if (dir) return JSON.parse(await readFile(join(dir, `${name}.json`), 'utf8'));
  const url = `https://raw.githubusercontent.com/${REPO}/${COMMIT}/src/data/${name}.json`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.json();
}

const [questions, worlds, practice] = await Promise.all(
  ['questions', 'worlds', 'practice'].map(load),
);

// Deterministic shuffle seeded by question id: the source data almost always
// lists the correct option first, so options are reordered stably here.
function seed(str) {
  let h = 2166136261;
  for (const c of str) h = Math.imul(h ^ c.codePointAt(0), 16777619);
  return h >>> 0;
}
function shuffled(items, id) {
  let s = seed(id);
  const rand = () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const a = [...items];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

const LETTERS = 'ABCDEFGH';
const num = (id, re) => Number(id.match(re)?.[1] ?? 0);
const byOrder = (a, b) =>
  num(a.world, /^w(\d+)/) - num(b.world, /^w(\d+)/) ||
  num(a.unit, /u(\d+)/) - num(b.unit, /u(\d+)/) ||
  num(a.lesson, /l(\d+)$/) - num(b.lesson, /l(\d+)$/) ||
  a.q_index.localeCompare(b.q_index);

const comment = (text) =>
  text.split('\n').map((l) => `-- ${l}`.trimEnd()).join('\n');

const KIND = {
  MC: 'Multiple choice',
  FIB: 'Fill in the blank',
  PO: 'Predict the output',
  SE: 'Spot the error',
  ORD: 'Put in order',
};

const header = (title) => `/-! # ${title} -/`;
const ex = [];
const ans = [];

ex.push(`import Mathlib

/-!
# LeanLingo exercises

Ported from LeanLingo (https://leanlingo.org, MIT, © Kenneth Jusino),
which draws on the official Lean books. Generated by \`scripts/port.mjs\`.

* Quiz questions are comments: write your answer on the \`-- your answer:\` line.
* "Predict the output" code is commented out: guess first, then uncomment and
  run it to check.
* Each world ends with a practice exercise: replace every \`sorry\`, then
  uncomment its \`-- #eval\` checks.
* Answers live in \`LeanLingo/Answers.lean\`, keyed by question id.
-/
`);
ans.push(`/-!
# LeanLingo answers

Answers and explanations for \`LeanLingo/Exercises.lean\`, keyed by question id.
Spoilers below.
-/
`);

const sorted = [...questions].sort(byOrder);

for (const w of worlds) {
  const n = num(w.id, /^w(\d+)/);
  const qs = sorted.filter((q) => q.world === w.id);
  ex.push(header(`World ${n}: ${w.title}`));
  if (w.blurb) ex.push(comment(w.blurb));
  ex.push('');
  ans.push(header(`World ${n}: ${w.title}`), '');

  let lesson = null;
  for (const q of qs) {
    if (q.lesson !== lesson) {
      lesson = q.lesson;
      ex.push(`/-! ## ${q.lesson} · ${q.lesson_title} (${q.book_ref}) -/`);
      ex.push(`-- Read: ${q.source_url}`, '');
    }
    const out = [`-- [${q.id}] ${KIND[q.type]}`, comment(q.prompt)];
    if (q.code) out.push('--', comment(q.code.replace(/^/gm, '    ')));
    const answerLines = [];

    if (q.type === 'MC' || q.type === 'SE') {
      const opts = shuffled(q.options, q.id);
      out.push('--');
      opts.forEach((o, i) => out.push(comment(`  ${LETTERS[i]}) ${o}`)));
      const i = opts.indexOf(q.answer);
      answerLines.push(`${LETTERS[i]}) ${q.answer}`);
    } else if (q.type === 'ORD') {
      out.push('--');
      q.ord_items.forEach((o, i) => out.push(comment(`  ${i + 1}. ${o}`)));
      answerLines.push(...q.answer.split(' | ').map((s, i) => `${i + 1}. ${s}`));
    } else {
      answerLines.push(q.answer);
    }
    out.push('-- your answer:', '');
    ex.push(...out);

    const indented = (t) => comment(t.replace(/^/gm, '  '));
    ans.push(`-- [${q.id}]`, indented(answerLines.join('\n')));
    if (q.explanation) ans.push(indented(q.explanation));
    if (q.quote) ans.push(indented(`Book: “${q.quote}”`));
    ans.push('');
  }

  for (const p of practice.filter((p) => p.world === w.id)) {
    ex.push(`/-! ## Practice: ${p.title} (${p.book_ref}) -/`);
    ex.push(`-- Read: ${p.source_url}`, comment(p.prompt), '');
    ex.push(`namespace LeanLingo.W${n}`, '');
    // #eval refuses to run code that depends on `sorry`, so checks stay
    // commented until the definitions are filled in.
    ex.push(p.starterCode.replace(/^(\s*)#eval/gm, '$1-- #eval'));
    ex.push('', `end LeanLingo.W${n}`, '');
  }
}

await writeFile('LeanLingo/Exercises.lean', ex.join('\n'));
await writeFile('LeanLingo/Answers.lean', ans.join('\n'));
console.log(`wrote ${questions.length} questions and ${practice.length} practice exercises`);
